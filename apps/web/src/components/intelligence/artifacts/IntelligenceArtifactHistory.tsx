/*                         Artifact Details                                   */
/* -------------------------------------------------------------------------- */

interface ArtifactDetailsProps {
    artifact: IntelligenceArtifact;
    onClose: () => void;
    onArtifactSigned: (
        artifact: IntelligenceArtifact,
    ) => void;
}

function ArtifactDetails({
    artifact,
    onClose,
    onArtifactSigned,
}: ArtifactDetailsProps) {
    const lineage =
        getArtifactFamily(
            artifact.artifactId,
        );
    const [
        trustAssessment,
        setTrustAssessment,
    ] =
        useState<
            IntelligenceArtifactTrustAssessment | null
        >(null);
    useEffect(() => {
        let cancelled = false;

        async function evaluateTrust() {
            try {
                const assessment =
                    await assessArtifactTrust(
                        artifact,
                    );

                if (!cancelled) {
                    setTrustAssessment(
                        assessment,
                    );
                }
            } catch (error) {
                console.error(
                    "Failed to assess artifact trust:",
                    error,
                );

                if (!cancelled) {
                    setTrustAssessment(
                        null,
                    );
                }
            }
        }

        void evaluateTrust();

        return () => {
            cancelled = true;
        };
    }, [artifact]);


    return (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 p-4 backdrop-blur-sm">
            <section className="max-h-[90vh] w-full max-w-3xl overflow-y-auto rounded-3xl border border-white/10 bg-zinc-950 p-6 shadow-2xl">
                <div className="flex items-start justify-between gap-4">
                    <div>
                        <p className="text-xs font-semibold uppercase tracking-[0.2em] text-cyan-400">
                            Intelligence Artifact
                        </p>

                        <h3 className="mt-2 text-2xl font-black text-white">
                            {artifact.metadata
                                .title ??
                                artifact.artifactType}
                        </h3>
                    </div>

                    <button
                        type="button"
                        onClick={onClose}
                        aria-label="Close artifact"
                        className="rounded-xl border border-white/10 p-2 text-zinc-500 transition hover:bg-white/[0.05] hover:text-white"
                    >
                        <X className="h-4 w-4" />
                    </button>
                </div>

                {/* ------------------------------------------------------------------ */}
                {/* Artifact Metadata                                                  */}
                {/* ------------------------------------------------------------------ */}

                <div className="mt-6 grid gap-4 sm:grid-cols-2">
                    <ArtifactField
                        label="Artifact ID"
                        value={
                            artifact.artifactId
                        }
                    />

                    <ArtifactField
                        label="Type"
                        value={
                            artifact.artifactType
                        }
                    />

                    <ArtifactField
                        label="Repository"
                        value={
                            artifact.repository
                        }
                    />

                    <ArtifactField
                        label="Version"
                        value={
                            artifact.version
                        }
                    />

                    <ArtifactField
                        label="Format"
                        value={
                            artifact.format
                        }
                    />

                    <ArtifactField
                        label="Status"
                        value={
                            artifact.status
                        }
                    />

                    <ArtifactField
                        label="Author"
                        value={
                            artifact.author
                        }
                    />

                    <ArtifactField
                        label="Source"
                        value={
                            artifact.source
                        }
                    />

                    <ArtifactField
                        label="Source Snapshot"
                        value={
                            artifact.sourceSnapshotId
                        }
                    />

                    <ArtifactField
                        label="Created"
                        value={
                            artifact.createdAt
                        }
                    />

                    <ArtifactField
                        label="Generated"
                        value={
                            artifact.generatedAt
                        }
                    />

                    {artifact.previousArtifactId ? (
                        <ArtifactField
                            label="Previous Artifact"
                            value={
                                artifact.previousArtifactId
                            }
                        />
                    ) : null}
                </div>

                <div className="mt-6">
                    <ArtifactLifecycleControls
                        artifact={artifact}
                        onUpdated={onArtifactSigned}
                    />
                </div>
                {/* ------------------------------------------------------------------ */}
                {/* Artifact Lineage                                                   */}
                {/* ------------------------------------------------------------------ */}

                <IntelligenceArtifactLineage
                    artifacts={lineage}
                    currentArtifactId={
                        artifact.artifactId
                    }
                />

                <IntelligenceArtifactExportButtons
                    artifactId={
                        artifact.artifactId
                    }
                />
                <IntelligenceArtifactIntegrity
                    artifactId={
                        artifact.artifactId
                    }
                    hasIntegrity={
                        Boolean(
                            artifact.integrity,
                        )
                    }
                    hash={
                        artifact.integrity?.hash
                    }
                />
                <IntelligenceArtifactSigningPanel
                    artifact={artifact}
                    onSigned={onArtifactSigned}
                />
                {trustAssessment ? (
                    <IntelligenceArtifactTrust
                        assessment={
                            trustAssessment
                        }
                        signerName={
                            artifact.signature
                                ?.signerName
                        }
                        signerId={
                            artifact.signature
                                ?.signerId
                        }
                        signedAt={
                            artifact.signature
                                ?.signedAt
                        }
                    />
                ) : (
                    <section className="mt-6 rounded-2xl border border-white/10 bg-white/[0.02] p-4">
                        <p className="text-xs font-semibold uppercase tracking-[0.2em] text-cyan-400">
                            Trust
                        </p>

                        <p className="mt-2 text-sm text-zinc-500">
                            Evaluating artifact trust...
                        </p>
                    </section>
                )}

                {/* ------------------------------------------------------------------ */}
                {/* Description                                                        */}
                {/* ------------------------------------------------------------------ */}

                {artifact.metadata
                    .description ? (
                    <div className="mt-6 rounded-2xl border border-white/10 bg-white/[0.02] p-4">
                        <p className="text-xs font-semibold uppercase tracking-wider text-zinc-500">
                            Description
                        </p>

                        <p className="mt-2 text-sm leading-6 text-zinc-300">
                            {
                                artifact.metadata
                                    .description
                            }
                        </p>
                    </div>
                ) : null}

                {/* ------------------------------------------------------------------ */}
                {/* Tags                                                               */}
                {/* ------------------------------------------------------------------ */}

                {artifact.metadata.tags
                    ?.length ? (
                    <div className="mt-4 flex flex-wrap gap-2">
                        {artifact.metadata.tags.map(
                            (tag) => (
                                <span
                                    key={tag}
                                    className="rounded-full border border-white/10 px-3 py-1 text-xs text-zinc-400"
                                >
                                    {tag}
                                </span>
                            ),
                        )}
                    </div>
                ) : null}
            </section>
        </div>
    );
}

