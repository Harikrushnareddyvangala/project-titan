/*                         Artifact Lifecycle Controls                         */
/* -------------------------------------------------------------------------- */

function ArtifactLifecycleControls({
    artifact,
    onUpdated,
}: {
    artifact: IntelligenceArtifact;
    onUpdated: (
        artifact: IntelligenceArtifact,
    ) => void;
}) {
    const status =
        artifact.status ??
        "Registered";

    const allowedTransitions =
        getAllowedArtifactStatusTransitions(
            status,
        );

    function transition(
        nextStatus: IntelligenceArtifact["status"],
    ) {
        if (!nextStatus) {
            return;
        }

        let updated:
            IntelligenceArtifact | null =
            null;

        if (
            nextStatus ===
            "Published"
        ) {
            updated =
                publishIntelligenceArtifact(
                    artifact.artifactId,
                );
        }

        if (
            nextStatus ===
            "Superseded"
        ) {
            updated =
                supersedeIntelligenceArtifact(
                    artifact.artifactId,
                );
        }

        if (
            nextStatus ===
            "Archived"
        ) {
            updated =
                archiveIntelligenceArtifact(
                    artifact.artifactId,
                );
        }

        if (updated) {
            onUpdated(updated);
        }
    }

    return (
        <section className="mt-6 rounded-2xl border border-white/10 bg-white/[0.02] p-4">
            <div className="flex items-center justify-between gap-4">
                <div>
                    <p className="text-xs font-semibold uppercase tracking-[0.2em] text-cyan-400">
                        Lifecycle
                    </p>

                    <p className="mt-1 text-sm text-zinc-500">
                        Controlled artifact state
                        transitions.
                    </p>
                </div>

                <IntelligenceArtifactStatusBadge
                    status={
                        artifact.status
                    }
                />
            </div>

            {allowedTransitions.length >
            0 ? (
                <div className="mt-4 flex flex-wrap gap-2">
                    {allowedTransitions.map(
                        (
                            nextStatus,
                        ) => {
                            if (
                                nextStatus ===
                                "Registered"
                            ) {
                                return null;
                            }

                            return (
                                <button
                                    key={
                                        nextStatus
                                    }
                                    type="button"
                                    onClick={() =>
                                        transition(
                                            nextStatus,
                                        )
                                    }
                                    className="rounded-xl border border-white/10 bg-white/[0.03] px-3 py-2 text-xs font-semibold text-zinc-300 transition hover:border-cyan-400/30 hover:bg-cyan-400/[0.05] hover:text-white"
                                >
                                    {nextStatus}
                                </button>
                            );
                        },
                    )}
                </div>
            ) : (
                <p className="mt-4 text-xs text-zinc-600">
                    No further lifecycle
                    transitions are available.
                </p>
            )}
        </section>
    );
}
